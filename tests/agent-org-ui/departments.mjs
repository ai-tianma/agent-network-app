import { run } from './harness.mjs';

await run(new URL('./artifacts/departments/', import.meta.url).pathname, async ({ c, page, test, shot, navigate, state, mode }) => {
  const el = id => page.getByTestId(`agent-org-${id}`);
  const saved = async () => { await el('department-editor').waitFor({ state: 'hidden' }); await el('department-result').waitFor(); };
  const focus = async id => {
    if (c.phone && await el('back').count()) await el('back').click();
    await el(`dept-${id}`).click();
  };
  await navigate('agentTeams'); await el('tree').waitFor();
  test('full App Settings navigation', true);
  await shot('tree');
  await el('new-department').click();
  test('shared human and Agent tree warning', /共用|共享/.test(await el('shared-tree-note').innerText()));
  test('blank name cannot submit', await el('department-save').getAttribute('aria-disabled') === 'true');
  await el('department-name').fill('   ');
  test('whitespace validation no writes', await el('department-validation').isVisible() && (await state()).writes.length === 0);
  await el('department-name').fill('Fixture New Root');
  await shot('new-root-dialog');
  const dialog = await el('department-editor').boundingBox();
  test('department dialog bounded on native-shaped viewport', dialog && dialog.x >= 0 && dialog.y >= 0 && dialog.x + dialog.width <= c.width + 1 && dialog.y + dialog.height <= c.height + 1, dialog);
  test('editing without submit does not mutate', (await state()).writes.length === 0);
  await el('department-save').click(); await saved();
  let s = await state(); const root = s.departments.find(d => d.name === 'Fixture New Root');
  test('root POST returns department and refreshes tree', s.writes.length === 1 && s.writes[0].method === 'POST' && s.writes[0].body.parent_id === null && !!root && (c.phone || await el(`dept-${root.id}`).count() === 1), s.writes);
  test('save triggers fresh department GET', s.requests.slice(s.requests.findIndex(r => r.method === 'POST') + 1).some(r => r.method === 'GET' && r.path.endsWith('/departments')));
  await el('new-child').click();
  test('child defaults to focused parent', (await el('department-parent-value').innerText()).includes('Fixture New Root'));
  await el('department-name').fill('Fixture Child'); await el('department-save').click(); await saved();
  s = await state(); const child = s.departments.find(d => d.name === 'Fixture Child');
  test('child POST exact parent contract', child?.parent_id === root.id && JSON.stringify(s.writes[1].body) === JSON.stringify({ name: 'Fixture Child', parent_id: root.id }));
  await el('rename-department').click(); await el('department-name').fill('Fixture Renamed'); await el('department-save').click(); await saved();
  s = await state();
  test('rename PATCH preserves parent and metadata', JSON.stringify(s.writes[2].body) === JSON.stringify({ name: 'Fixture Renamed' }) && s.departments.find(d => d.id === child.id)?.parent_id === root.id);
  await focus(root.id); await el('reparent-department').click();
  test('reparent excludes self and descendants', await el(`parent-${root.id}`).count() === 0 && await el(`parent-${child.id}`).count() === 0 && await el('parent-root').count() === 1);
  await el('department-parent-search').fill('Station Alpha');
  test('parent picker search', await el('parent-station-a').count() === 1 && await el('parent-tmai').count() === 0);
  await shot('reparent-dialog');
  await el('parent-station-a').click(); await el('department-save').click(); await saved(); s = await state();
  test('reparent PATCH only parent_id', JSON.stringify(s.writes[3].body) === JSON.stringify({ parent_id: 'station-a' }) && s.departments.find(d => d.id === root.id)?.parent_id === 'station-a');
  await navigate('agentTeams'); await el('tree').waitFor(); await focus(root.id);
  if (c.phone) test('rename and reparent persist after reload', (await el('detail').innerText()).includes('Fixture Renamed'));
  else test('rename and reparent persist after reload', await el(`dept-${child.id}-label`).innerText() === 'Fixture Renamed' && (await state()).departments.find(d => d.id === root.id)?.parent_id === 'station-a');
  await mode('fail=1'); await el('rename-department').click(); await el('department-name').fill('Must Not Save'); await el('department-save').click(); await el('department-error').waitFor();
  s = await state();
  test('server failure keeps editor and no false success', s.writes.at(-1).status === 500 && s.departments.find(d => d.id === root.id)?.name === 'Fixture New Root' && await el('department-result').count() === 0);
  await shot('server-failure'); await page.keyboard.press('Escape');
  await mode(''); await el('new-department').click(); await el('department-name').fill('Refresh Recovery'); await mode('refreshFail=1');
  await el('department-save').click(); await el('department-error').waitFor(); s = await state(); const writesBeforeRetry = s.writes.length;
  test('confirmed write with failed refresh not reported successful', s.writes.at(-1).status === 200 && await el('department-result').count() === 0 && await el('department-editor').isVisible());
  await mode(''); await el('department-save').click(); await saved();
  test('refresh retry does not repeat POST', (await state()).writes.length === writesBeforeRetry);
  await el('rename-department').click(); await el('department-name').fill('Revoked Permission'); await mode('restricted=1');
  await el('department-save').click(); await el('department-error').waitFor(); s = await state();
  test('permission revoked before submit returns 403 without false success', s.writes.at(-1).status === 403 && s.departments.some(d => d.name === 'Refresh Recovery') && !s.departments.some(d => d.name === 'Revoked Permission') && await el('department-result').count() === 0);
  await shot('permission-revoked'); await page.keyboard.press('Escape');
  await mode('restricted=1'); await navigate('agentTeams'); await el('tree').waitFor(); await focus('tmai'); s = await state();
  const beforeDenied = s.writes.length;
  test('viewer_can denies child rename reparent controls', await el('new-child').count() === 0 && await el('rename-department').count() === 0 && await el('reparent-department').count() === 0);
  // Root permission is not part of Department.viewer_can; do not invent a wire field.
  test('denied department navigation issues no writes', (await state()).writes.length === beforeDenied);
  await shot('role-denied');
  test('native-shaped mobile and desktop no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  test('only expected fixture mutations', (await state()).unhandled.length === 0);
});
